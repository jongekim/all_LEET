import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { ANSWER_DATA } from '../supabase/functions/_shared/user-data-rules/answerData';
import { stableJSON } from '../supabase/functions/_shared/user-data-rules/stableJSON';

type Row = { year:string; subject:'verbal'|'reasoning'; canonical_question_id:string; odd_question_no:number; even_question_no:number; odd_choice_to_even:number[]; review_status:string };
async function main() {
const source = JSON.parse(await readFile('scripts/data/question-registry-reviewed.json','utf8')) as {questions:Row[];sources:Record<string,string>};
assert.equal(source.questions.length,1350);
assert.equal(Object.keys(source.sources).length,76);
const sha = (data:unknown) => createHash('sha256').update(stableJSON(data)).digest('hex');
if(process.argv.includes('--verify-sources')) {
  const buffers = await Promise.all(Object.keys(source.sources).map(async path=>[path,await readFile(path)] as const));
  for(const [path,buffer] of buffers) assert.equal(createHash('sha256').update(buffer).digest('hex'),source.sources[path]);
}
for(const hash of Object.values(source.sources)) assert.match(hash,/^[0-9a-f]{64}$/);
const cohorts = Object.keys(ANSWER_DATA).filter(year=>year!=='2027').sort().flatMap(year => (['verbal','reasoning'] as const).map(subject=>{
  const rows=source.questions.filter(r=>r.year===year&&r.subject===subject).sort((a,b)=>a.even_question_no-b.even_question_no);
  const answers=ANSWER_DATA[year][subject];
  assert.equal(rows.length,Object.keys(answers.even).length);
  assert.equal(new Set(rows.map(r=>r.odd_question_no)).size,rows.length);
  const questions=rows.map((r,i)=>{
    assert.equal(r.review_status,'source_visual_reviewed');
    assert.equal(r.even_question_no,i+1);
    assert.equal(r.canonical_question_id,`${year==='09예비'?'2009-preliminary':year}:${subject}:E${String(i+1).padStart(2,'0')}`);
    assert.ok(r.odd_question_no>=1&&r.odd_question_no<=rows.length);
    assert.equal([...r.odd_choice_to_even].sort().join(''),'12345');
    assert.equal(r.odd_choice_to_even[answers.odd[r.odd_question_no]-1],answers.even[i+1]);
    return {question_id:r.canonical_question_id,odd_question_no:r.odd_question_no,odd_choice_to_even:r.odd_choice_to_even};
  });
  return {year,subject,questions};
}));

const mapping_sha256=sha(cohorts);
const mapping_version='leet_forms_2026_10_12_v1';
const classification_version='fields-'+sha(Object.keys(ANSWER_DATA).sort().map(year=>({year,verbal:ANSWER_DATA[year].verbal.fieldMapping,reasoning:ANSWER_DATA[year].reasoning.fieldMapping})));
const catalog = {mapping_version,mapping_sha256,aggregation_version:'pooled_saved_answers_v2',cohorts:cohorts.map(c=>({
  ...c,question_count:c.questions.length,answer_key_version:`v1:${Object.values(ANSWER_DATA[c.year][c.subject].even).join('')}`,
  questions:c.questions.map((q,i)=>({...q,correct_answer:ANSWER_DATA[c.year][c.subject].even[i+1]})),
})),excluded_cohorts:(['verbal','reasoning'] as const).map(subject=>({year:'2027',subject,question_count:subject==='verbal'?30:40}))};
const catalog_sha256=sha(catalog);
const outputs:Record<string,string>={
  'supabase/functions/_shared/user-data-rules/questionRegistry.generated.ts':`// Generated by npm run registry:generate; do not edit. Reviewed 1,350 questions / 76 sources.\nexport const MAPPING_VERSION = ${JSON.stringify(mapping_version)};\nexport const MAPPING_SHA256 = ${JSON.stringify(mapping_sha256)};\nexport const CLASSIFICATION_VERSION = ${JSON.stringify(classification_version)};\nexport const CATALOG_SHA256 = ${JSON.stringify(catalog_sha256)};\nexport const CATALOG_ID = ${JSON.stringify('leet-'+catalog_sha256)};\nexport interface RegistryCohort { readonly year:string; readonly subject:'verbal'|'reasoning'; readonly questions:readonly {readonly question_id:string; readonly odd_question_no:number; readonly odd_choice_to_even:readonly number[]}[]; }\nexport const QUESTION_REGISTRY:readonly RegistryCohort[] = ${JSON.stringify(cohorts)};\n`,
  'scripts/data/question-statistics-catalog-v2.json':JSON.stringify({...catalog,catalog_id:'leet-'+catalog_sha256,catalog_sha256},null,2)+'\n',
  'scripts/data/question-registry-provenance.json':JSON.stringify({mapping_version,mapping_sha256,source_sha256:sha(source.sources),sources:source.sources},null,2)+'\n',
};
for(const [path,content] of Object.entries(outputs)) {
  if(process.argv.includes('--check')) assert.equal(await readFile(path,'utf8'),content,`${path}: regenerate registry`);
  else await writeFile(path,content);
}
console.log(`Registry ${process.argv.includes('--check')?'verified':'generated'}: 38 cohorts, 1350 IDs, ${mapping_sha256}`);

}
main().catch(error=>{console.error(error);process.exitCode=1;});
